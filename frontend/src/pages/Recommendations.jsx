import { useEffect, useState } from 'react';
import { useOutletContext, useNavigate, useParams, Link } from 'react-router-dom';
import { Download, ArrowLeft, ArrowRight, Trash2, FileText, CheckCircle2 } from 'lucide-react';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid } from 'recharts';
import { get, del } from '../services/api';
import { ConfirmModal, InfoModal, EmptyState, ErrorBanner } from '../components/ui';

export function RecommendationsList() {
  const { setCrumb } = useOutletContext();
  const navigate = useNavigate();
  const [recs, setRecs] = useState([]);
  const [error, setError] = useState('');
  const [toDelete, setToDelete] = useState(null);

  useEffect(() => { setCrumb('My Recommendations'); }, [setCrumb]);
  useEffect(() => { load(); }, []);

  async function load() {
    try {
      const d = await get('/recommendations');
      setRecs(d.recommendations);
    } catch (err) { setError(err.message); }
  }

  async function confirmDelete() {
    try {
      await del(`/recommendations/${toDelete.id}`);
      setToDelete(null);
      load();
    } catch (err) { setError(err.message); }
  }

  return (
    <div>
      <h1 className="text-2xl font-bold text-navy sm:text-[28px]">My Recommendations</h1>
      <p className="mt-1 text-[15px] text-muted">Your saved solar sizing reports, generated by the expert system.</p>
      <ErrorBanner message={error} />
      <div className="mt-6">
        {recs.length === 0 ? (
          <EmptyState title="No recommendations yet" message="Start a chat consultation to generate your first solar plan." />
        ) : (
          <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-3">
            {recs.map((r) => (
              <div key={r.id} className="rounded-2xl border border-line bg-white p-5 shadow-card fade-up">
                <div className="flex items-start justify-between">
                  <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-lightblue">
                    <FileText className="h-5 w-5 text-primary" />
                  </div>
                  <button onClick={() => setToDelete(r)} className="rounded-lg p-2 text-muted hover:bg-red-50 hover:text-red-600" title="Delete">
                    <Trash2 className="h-4 w-4" />
                  </button>
                </div>
                <h3 className="mt-3 text-base font-bold text-navy">{r.household_context || 'Home solar plan'}</h3>
                <p className="text-xs text-muted">#{r.reference} · {new Date(r.created_at).toLocaleDateString()}</p>
                <div className="mt-4 grid grid-cols-3 gap-2 text-center">
                  <div className="rounded-lg bg-appbg py-2"><p className="text-sm font-bold text-navy">{(r.pv_capacity_wp / 1000).toFixed(1)} kWp</p><p className="text-[11px] text-muted">PV array</p></div>
                  <div className="rounded-lg bg-appbg py-2"><p className="text-sm font-bold text-navy">{r.inverter_capacity_kw} kW</p><p className="text-[11px] text-muted">Inverter</p></div>
                  <div className="rounded-lg bg-appbg py-2"><p className="text-sm font-bold text-navy">{(r.battery_energy_wh / 1000).toFixed(1)} kWh</p><p className="text-[11px] text-muted">Battery</p></div>
                </div>
                <button onClick={() => navigate(`/recommendations/${r.id}`)}
                  className="mt-4 inline-flex items-center gap-1.5 text-sm font-semibold text-primary hover:underline">
                  View report <ArrowRight className="h-4 w-4" />
                </button>
              </div>
            ))}
          </div>
        )}
      </div>
      <ConfirmModal
        open={!!toDelete}
        title="Delete selected record?"
        message="This permanently removes the selected recommendation from your account. This action cannot be undone."
        confirmLabel="Delete record"
        onConfirm={confirmDelete}
        onCancel={() => setToDelete(null)}
      />
    </div>
  );
}

export function RecommendationDetail() {
  const { setCrumb } = useOutletContext();
  const navigate = useNavigate();
  const [rec, setRec] = useState(null);
  const [rules, setRules] = useState([]);
  const [error, setError] = useState('');
  const [reportReady, setReportReady] = useState(false);
  const { id } = useParams();

  useEffect(() => { setCrumb('My Recommendations'); }, [setCrumb]);
  useEffect(() => {
    get(`/recommendations/${id}`)
      .then((d) => setRec(d.recommendation))
      .catch((err) => setError(err.message));
    get('/rules').then((d) => setRules(d.rules)).catch(() => {});
  }, [id]);

  if (error) return <ErrorBanner message={error} />;
  if (!rec) return <p className="text-muted">Loading report…</p>;

  const triggeredDetails = rules.filter((r) => rec.triggered_rules?.includes(r.rule_code));
  const chartData = (rec.appliances || []).map((a) => ({
    name: a.name.length > 14 ? a.name.slice(0, 13) + '…' : a.name,
    watts: a.quantity * a.wattage_w,
  }));

  function downloadPdf() {
    setReportReady(true);
  }

  return (
    <div>
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-navy sm:text-[28px]">{rec.household_context || 'Home solar plan'}</h1>
          <p className="mt-1 text-sm text-muted">Recommendation report · #{rec.reference} · Generated {new Date(rec.created_at).toLocaleString()}</p>
        </div>
        <button onClick={downloadPdf} className="no-print inline-flex items-center gap-2 rounded-lg bg-primary px-5 py-2.5 text-sm font-semibold text-white hover:bg-primarydark">
          <Download className="h-4 w-4" /> Download PDF
        </button>
      </div>

      <div className="mt-5 flex items-center gap-2 rounded-xl bg-green-50 px-4 py-3 text-sm text-success">
        <CheckCircle2 className="h-4 w-4 shrink-0" />
        Recommendation saved to your account. Your {rec.backup_hours_target}-hour essential backup target is {rec.estimated_backup_hours >= rec.backup_hours_target ? 'met' : 'close to being met'} under the stated assumptions.
      </div>

      <div className="mt-5 grid grid-cols-2 gap-4 lg:grid-cols-4">
        {[
          { v: `${(rec.pv_capacity_wp / 1000).toFixed(1)} kWp`, l: `PV array · ${rec.pv_panel_count} × ${rec.pv_panel_wattage_w} W` },
          { v: `${rec.inverter_capacity_kw} kW`, l: 'Continuous inverter' },
          { v: `${(rec.battery_energy_wh / 1000).toFixed(2)} kWh`, l: `Nominal storage · ${rec.battery_voltage_v} V / ${rec.battery_capacity_ah} Ah` },
          { v: `~${rec.estimated_backup_hours} h`, l: `Backup at essential load (${rec.essential_load_w} W)` },
        ].map((c) => (
          <div key={c.l} className="rounded-2xl border border-line bg-white p-5 shadow-card">
            <p className="text-2xl font-bold text-navy">{c.v}</p>
            <p className="mt-1 text-xs text-muted">{c.l}</p>
          </div>
        ))}
      </div>

      <div className="mt-5 grid gap-5 lg:grid-cols-[1fr_340px]">
        <div className="space-y-5">
          <div className="rounded-2xl border border-line bg-white p-6 shadow-card">
            <h3 className="text-lg font-bold text-navy">Sizing calculations &amp; applied rules</h3>
            <div className="mt-4 space-y-4">
              {triggeredDetails.length === 0 && <p className="text-sm text-muted">Rules: {rec.triggered_rules?.join(', ') || '—'}</p>}
              {triggeredDetails.map((r) => (
                <div key={r.rule_code} className="flex gap-4">
                  <span className="w-16 shrink-0 pt-0.5 text-xs font-bold text-primary">{r.rule_code}</span>
                  <div>
                    <p className="text-sm font-semibold text-navy">{r.name}</p>
                    <p className="mt-0.5 text-[13px] text-muted">{r.description}</p>
                  </div>
                </div>
              ))}
            </div>
            <div className="mt-5 rounded-xl bg-appbg p-4">
              <p className="text-xs font-bold uppercase tracking-wider text-muted">Engineering explanation</p>
              <pre className="mt-2 whitespace-pre-wrap font-sans text-[13px] leading-relaxed text-navy">{rec.explanation}</pre>
            </div>
          </div>

          <div className="rounded-2xl border border-line bg-white p-6 shadow-card">
            <h3 className="text-lg font-bold text-navy">Appliance load breakdown</h3>
            <div className="mt-4 h-56">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={chartData} margin={{ top: 5, right: 10, left: 0, bottom: 5 }}>
                  <CartesianGrid strokeDasharray="3 3" stroke="#E2E8F0" />
                  <XAxis dataKey="name" tick={{ fontSize: 11, fill: '#64748B' }} interval={0} angle={-20} textAnchor="end" height={50} />
                  <YAxis tick={{ fontSize: 11, fill: '#64748B' }} />
                  <Tooltip formatter={(v) => [`${v} W`, 'Connected load']} />
                  <Bar dataKey="watts" fill="#2563EB" radius={[6, 6, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>
            <div className="mt-4 overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b border-line text-left text-xs uppercase tracking-wider text-muted">
                    <th className="py-2 pr-4 font-semibold">Appliance</th>
                    <th className="py-2 pr-4 font-semibold">Qty</th>
                    <th className="py-2 pr-4 font-semibold">Wattage</th>
                    <th className="py-2 pr-4 font-semibold">Hours/day</th>
                    <th className="py-2 font-semibold">Total</th>
                  </tr>
                </thead>
                <tbody>
                  {(rec.appliances || []).map((a) => (
                    <tr key={a.name} className="border-b border-line/60">
                      <td className="py-2.5 pr-4 text-navy">{a.name}</td>
                      <td className="py-2.5 pr-4 text-navy">{a.quantity}</td>
                      <td className="py-2.5 pr-4 text-navy">{a.wattage_w} W</td>
                      <td className="py-2.5 pr-4 text-navy">{a.hours_per_day} h</td>
                      <td className="py-2.5 font-medium text-navy">{(a.quantity * a.wattage_w).toLocaleString()} W</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </div>

        <div className="space-y-5">
          <div className="rounded-2xl border border-line bg-white p-6 shadow-card">
            <h3 className="text-lg font-bold text-navy">Design assumptions</h3>
            <p className="mt-3 text-[11px] font-bold uppercase tracking-wider text-primary">Home &amp; load</p>
            <p className="mt-1.5 text-sm leading-relaxed text-muted">
              {rec.household_context || 'Home'} · {Number(rec.total_load_w).toLocaleString()} W connected<br />
              {(rec.daily_energy_wh / 1000).toFixed(2)} kWh/day estimated usage<br />
              {rec.backup_hours_target}-hour essential backup target
            </p>
            <p className="mt-4 text-[11px] font-bold uppercase tracking-wider text-primary">Operating conditions</p>
            <ul className="mt-1.5 space-y-1 text-sm text-muted">
              {(rec.assumptions || []).map((a) => <li key={a}>• {a}</li>)}
            </ul>
          </div>
          <div className="rounded-2xl bg-lightblue p-6">
            <h3 className="text-[15px] font-bold text-navy">Before installation</h3>
            <p className="mt-2 text-sm leading-relaxed text-navy">
              Confirm appliance run times, refrigerator start-up surge, roof shading, local irradiance and equipment voltage compatibility.
              A qualified installer must verify protection devices, cable sizing, earthing and applicable electrical standards.
            </p>
          </div>
        </div>
      </div>

      <div className="no-print mt-6 flex flex-wrap items-center justify-between gap-3">
        <Link to="/recommendations" className="inline-flex items-center gap-2 rounded-lg border border-line bg-white px-5 py-2.5 text-sm font-semibold text-navy hover:bg-appbg">
          <ArrowLeft className="h-4 w-4" /> Back to recommendations
        </Link>
        <Link to="/advisor" className="inline-flex items-center gap-2 rounded-lg bg-primary px-5 py-2.5 text-sm font-semibold text-white hover:bg-primarydark">
          Continue this conversation <ArrowRight className="h-4 w-4" />
        </Link>
      </div>

      <InfoModal
        open={reportReady}
        title="Your report is ready"
        message={`${rec.reference} · ${rec.household_context || 'Home'} — PDF report includes requirements, sizing calculations, expert rules and planning assumptions. Use your browser's print dialog to save as PDF.`}
        onClose={() => { setReportReady(false); setTimeout(() => window.print(), 200); }}
      />
    </div>
  );
}
