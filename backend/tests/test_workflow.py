"""End-to-end workflow test mirroring the acceptance checklist in the brief."""
from tests.conftest import auth


def test_complete_end_to_end_workflow(client):
    # 1. Register a general user
    r = client.post("/api/auth/register", json={
        "name": "Workflow User", "email": "workflow@example.com", "password": "Workflow@123"})
    assert r.status_code == 201
    user_token = r.get_json()["token"]
    assert r.get_json()["user"]["role"] == "user"

    # 2. Log in
    r = client.post("/api/auth/login", json={"email": "workflow@example.com", "password": "Workflow@123"})
    assert r.status_code == 200
    h = auth(user_token)

    # 3. Enter household requirements (appliances only)
    r = client.post("/api/chat", headers=h, json={
        "message": "I have 4 fans, 8 LED lights, one refrigerator, one LED TV and a washing machine.",
        "history": []})
    data = r.get_json()
    assert data["recommendation"] is None
    assert data["questions"], "must ask a clarification question instead of guessing"
    history = [{"role": "user", "content": "I have 4 fans, 8 LED lights, one refrigerator, one LED TV and a washing machine."}]

    # 4. Answer the clarification question (backup hours)
    r = client.post("/api/chat", headers=h, json={"message": "I need backup for around 8 hours.", "history": history})
    data = r.get_json()
    rec = data["recommendation"]
    assert rec is not None

    # 5. Recommendation generated by the rule engine
    assert round(rec["total_load_w"]) == 2112
    assert rec["inverter_capacity_kw"] == 3.0
    assert rec["pv_capacity_wp"] == 3300.0
    assert rec["pv_panel_count"] == 6
    assert rec["battery_voltage_v"] == 51.2
    assert rec["estimated_backup_hours"] >= 8.0
    assert "INV-002" in rec["triggered_rules"]
    assert "PV-004" in rec["triggered_rules"]
    assert "BAT-003" in rec["triggered_rules"]

    # 6. View calculation details
    r = client.get(f"/api/recommendations/{rec['id']}", headers=h)
    detail = r.get_json()["recommendation"]
    assert len(detail["appliances"]) == 5
    assert detail["explanation"]
    assert detail["assumptions"]

    # 7. Recommendation already saved on generation; also confirm the list endpoint
    r = client.get("/api/recommendations", headers=h)
    assert any(x["id"] == rec["id"] for x in r.get_json()["recommendations"])

    # 7b. General user is blocked from admin APIs (RBAC)
    assert client.get("/api/admin/stats", headers=h).status_code == 403

    # 8. Log in as administrator
    r = client.post("/api/auth/login", json={"email": "admin@solaradvisor.com", "password": "Admin@12345"})
    assert r.status_code == 200
    ah = auth(r.get_json()["token"])

    # 9. Add then edit a knowledge-base fact
    r = client.post("/api/admin/knowledge", headers=ah, json={
        "title": "Workflow test fact", "category": "Testing",
        "description": "Created by the automated workflow test.", "value_text": "1 kW"})
    assert r.status_code == 201
    fid = r.get_json()["fact"]["id"]
    r = client.patch(f"/api/admin/knowledge/{fid}", headers=ah, json={"value_text": "1.5 kW"})
    assert r.get_json()["fact"]["value_text"] == "1.5 kW"

    # 10. Create a rule
    r = client.post("/api/admin/rules", headers=ah, json={
        "rule_code": "WF-001", "name": "Workflow rule", "condition_field": "total_load_w",
        "operator": "gte", "threshold_value": 500, "description": "Test-only rule.",
        "explanation_template": "Connect load {total_load_w} W."})
    assert r.status_code == 201
    rid = r.get_json()["rule"]["id"]

    # 11. Test the rule through the sandbox — the new rule must appear in the trace
    r = client.post("/api/admin/test-rules", headers=ah, json={
        "text": "I have 4 fans, 8 lights, one fridge and need 8 hours of backup."})
    assert r.status_code == 200
    codes = [t["rule_code"] for t in r.get_json()["recommendation"]["trace"]]
    assert "WF-001" in codes
    assert r.get_json()["recommendation"]["triggered_rules"].count("WF-001") == 1

    # 12. Inspect the inference trace
    r = client.get("/api/admin/traces", headers=ah)
    traces = r.get_json()["traces"]
    assert traces and traces[0]["trace"]
    assert traces[0]["facts"]["total_load_w"] > 0

    # Cleanup created admin records
    assert client.delete(f"/api/admin/rules/{rid}", headers=ah).status_code == 200
    assert client.delete(f"/api/admin/knowledge/{fid}", headers=ah).status_code == 200
